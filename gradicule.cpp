gradicule::gradicule(projection* p) : m_proj(p)
{
  worldGradicule();                        // build world gradicule
}

gradicule::~gradicule()
{

}

/**********************************************************************************************************************
 * Function: worldGradicule
 *
 * Abstract: This builds the grid system in world coordinates (most likely on a unit sphere).  The coordinates are 
 *           built in 'row-order' form, i.e. all the points for 90 degrees north latitude, then 90-deltaLat, and so on.  
 *           There will be 2\pi/\DeltaLon points per row.
 *           The range for latitude is [0, 180] and the range for longidude is [=180, 180).  angles are stored in 
 *           radians not degrees.
 *           For example if deltaLon = 30 and deltaLat = 15 the points generated would be,
 * (-180,  0),(-150,  0),(-120,  0),(-90,  0),(-60,  0),(-30,  0),(0,  0),(30,  0),(60,  0),(90,  0),(120,  0),(150,  0)
 * (-180, 15),(-150, 15),(-120, 15),(-90, 15),(-60, 15),(-30, 15),(0, 15),(30, 15),(60, 15),(90, 15),(120, 15),(150, 15)
 * (-180, 30),(-150, 30),(-120, 30),(-90, 30),(-60, 30),(-30, 30),(0, 30),(30, 30),(60, 30),(90, 30),(120, 30),(150, 30)
 * (-180, 45),(-150, 45),(-120, 45),(-90, 45),(-60, 45),(-30, 45),(0, 45),(30, 45),(60, 45),(90, 45),(120, 45),(150, 45)
 * (-180, 60),(-150, 60),(-120, 60),(-90, 60),(-60, 60),(-30, 60),(0, 60),(30, 60),(60, 60),(90, 60),(120, 60),(150, 60)
 * (-180, 75),(-150, 75),(-120, 75),(-90, 75),(-60, 75),(-30, 75),(0, 75),(30, 75),(60, 75),(90, 75),(120, 75),(150, 75)
 * (-180, 90),(-150, 90),(-120, 90),(-90, 90),(-60, 90),(-30, 90),(0, 90),(30, 90),(60, 90),(90, 90),(120, 90),(150, 90)
 * (-180,105),(-150,105),(-120,105),(-90,105),(-60,105),(-30,105),(0,105),(30,105),(60,105),(90,105),(120,105),(150,105)
 * (-180,120),(-150,120),(-120,120),(-90,120),(-60,120),(-30,120),(0,120),(30,120),(60,120),(90,120),(120,120),(150,120)
 * (-180,135),(-150,135),(-120,135),(-90,135),(-60,135),(-30,135),(0,135),(30,135),(60,135),(90,135),(120,135),(150,135)
 * (-180,150),(-150,150),(-120,150),(-90,150),(-60,150),(-30,150),(0,150),(30,150),(60,150),(90,150),(120,150),(150,150)
 * (-180,165),(-150,165),(-120,165),(-90,165),(-60,165),(-30,165),(0,165),(30,165),(60,165),(90,165),(120,165),(150,165)
 * (-180,180),(-150,180),(-120,180),(-90,180),(-60,180),(-30,180),(0,180),(30,180),(60,180),(90,180),(120,180),(150,180)
 *
 * Input   :
 *
 * Returns :
 *
 * Written : Nov 2026 (gkhuber) 
 *********************************************************************************************************************/
void gradicule::worldGradicule()
{
  for (int32_t lat = 0; lat <= 180; lat += deltaLat)
  {
    for (int32_t lon = -180; lon < 180; lon += deltaLon)
    {
      m_pts.push_back({ lon*DEG2RAD, lat*DEG2RAD });
    }
  }
}


/**********************************************************************************************************************
 * Function: mapGradicule
 *
 * Abstract: converts the world gradicule points into map coordinates under the current projection.
 *
 * Input   :
 *
 * Returns :
 *
 * Written : Nov 2026 (gkhuber)  
 *********************************************************************************************************************/
 void gradicule::mapGradicule()
{
   if (m_proj != nullptr)
   {
     for (auto [lon, lat] : m_pts)
     {
       std::pair<double_t, double_t> xformCoords = m_proj->convert(lat, lon);
       m_mapPts.push_back({ xformCoords.second, xformCoords.first });
     }
   }
}
